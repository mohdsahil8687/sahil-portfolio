create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 100),
  email text not null check (char_length(email) between 5 and 254 and email like '%@%'),
  contact_number text not null default '' check (char_length(contact_number) <= 40),
  project_type text not null default '',
  message text not null check (char_length(message) between 10 and 3000),
  status text not null default 'new' check (status in ('new','contacted','closed')),
  created_at timestamptz not null default now()
);
create table if not exists public.page_views (
  id bigint generated by default as identity primary key,
  path text not null check (char_length(path) <= 160),
  visitor_id text not null check (char_length(visitor_id) between 10 and 80),
  created_at timestamptz not null default now()
);
create index if not exists page_views_created_idx on public.page_views (created_at desc);
create table if not exists public.member_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null default '',
  marketing_opt_in boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

